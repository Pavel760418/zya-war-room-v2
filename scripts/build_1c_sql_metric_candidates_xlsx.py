def write_sheet_from_dicts(ws, rows, yellow_cols=None, red_obligatory_col=None):
    if not rows:
        return
    cols = list(rows[0].keys())
    for c, name in enumerate(cols, 1):
        ws.cell(row=1, column=c, value=name)
    style_header(ws, len(cols))
    yellow_cols = yellow_cols or set()
    for i, row in enumerate(rows, 2):
        for c, key in enumerate(cols, 1):
            cell = ws.cell(row=i, column=c, value=row.get(key))
            cell.font = NORMAL
            cell.alignment = WRAP
            cell.border = THIN
            if key in yellow_cols:
                cell.fill = YELLOW
        if red_obligatory_col and "Метрика" in cols:
            req = row.get(red_obligatory_col)
            # highlight mandatory metrics without confirmed high-confidence source
            if req == "Да" and (
                row.get("Уровень уверенности") in {C_UNK, C_LOW}
                or row.get("Статус поиска") in {S_NO, S_1C, S_IT, S_MULTI}
            ):
                ws.cell(row=i, column=cols.index("Метрика") + 1).fill = RED
    freeze_filter(ws)


